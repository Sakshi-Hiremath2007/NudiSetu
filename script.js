function updateLearningStreak() {
  const today = new Date().toLocaleDateString("en-CA");
  const lastVisit = localStorage.getItem("nudisetuLastVisit");
  let streak = Number(localStorage.getItem("nudisetuLearningStreak")) || 0;

  if (lastVisit !== today) {
    if (lastVisit) {
      const previousDate = new Date(lastVisit + "T12:00:00");
      const currentDate = new Date(today + "T12:00:00");

      const difference = Math.round(
        (currentDate - previousDate) / (1000 * 60 * 60 * 24),
      );

      streak = difference === 1 ? streak + 1 : 1;
    } else {
      streak = 1;
    }

    localStorage.setItem("nudisetuLastVisit", today);
    localStorage.setItem("nudisetuLearningStreak", streak);
  }

  const streakDisplay = document.getElementById("learning-streak-count");

  if (streakDisplay) {
    streakDisplay.textContent = streak;
  }
}

updateLearningStreak();
