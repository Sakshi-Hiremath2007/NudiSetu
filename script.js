const progressKey = "nudisetu-completed-lessons";

function getCompletedLessons() {
  try {
    const saved = JSON.parse(localStorage.getItem(progressKey) || "[]");

    return Array.isArray(saved)
      ? saved.filter((item) => typeof item === "string")
      : [];
  } catch {
    return [];
  }
}

function saveCompletedLesson(category) {
  const completed = getCompletedLessons();

  if (!completed.includes(category)) {
    completed.push(category);
    localStorage.setItem(progressKey, JSON.stringify(completed));
  }

  updateProgressDisplay();
  updateBadgeRewards();
  updateLearningPath();
  checkStageCelebration();
}

function updateProgressDisplay() {
  const completed = getCompletedLessons();
  const display = document.getElementById("learning-progress");

  if (display) {
    display.textContent = `${completed.length} of 12 learning categories explored`;
  }
}

