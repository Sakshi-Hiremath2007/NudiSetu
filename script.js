function updateLearningPath() {
  const completed = getCompletedLessons();

  const stages = {
    beginner: {
      title: "Beginner",
      categories: ["greetings", "everyday", "family", "numbers"],
    },
    intermediate: {
      title: "Intermediate",
      categories: ["college", "shopping", "food", "travel"],
    },
    advanced: {
      title: "Advanced",
      categories: ["hospital", "emergency", "culture", "home"],
    },
  };

  const categoryNames = {
    greetings: "Greetings",
    everyday: "Everyday Kannada",
    family: "Family",
    numbers: "Numbers",
    college: "College Life",
    shopping: "Shopping",
    food: "Food",
    travel: "Travel",
    hospital: "Hospital",
    emergency: "Emergency Kannada",
    culture: "Karnataka Culture",
    home: "Home",
  };

  const isComplete = (category) => completed.includes(category);

  // Update each stage's progress and status
  Object.entries(stages).forEach(([key, stage], index) => {
    const explored = stage.categories.filter(isComplete).length;
    const allComplete = explored === stage.categories.length;

    const card = document.getElementById(`path-${key}`);
    const status = document.getElementById(`path-${key}-status`);
    const progress = document.getElementById(`path-${key}-progress`);
    const fill = document.getElementById(`path-${key}-fill`);

    if (!card || !status || !progress || !fill) return;

    progress.textContent = `${explored} of ${stage.categories.length} categories explored`;

    fill.style.width = `${(explored / stage.categories.length) * 100}%`;

    card.classList.toggle("completed", allComplete);
    card.classList.remove("active", "locked");

    const previousStageComplete =
      index === 0 ||
      stages[Object.keys(stages)[index - 1]].categories.every(isComplete);

    if (allComplete) {
      status.textContent = "COMPLETED ✓";
    } else if (previousStageComplete) {
      status.textContent = index === 0 ? "START HERE" : "IN PROGRESS";
      card.classList.add("active");
    } else {
      status.textContent = "COMING UP";
      card.classList.add("locked");
    }
  });

  /* NudiSetu — Stage completion celebration */

  function checkStageCelebration() {
    const completed = getCompletedLessons();

    const stages = {
      beginner: {
        title: "Beginner",
        categories: ["greetings", "everyday", "family", "numbers"],
      },
      intermediate: {
        title: "Intermediate",
        categories: ["college", "shopping", "food", "travel"],
      },
      advanced: {
        title: "Advanced",
        categories: ["hospital", "emergency", "culture", "home"],
      },
    };

    const celebration = document.getElementById("stage-celebration");
    const title = document.getElementById("stage-celebration-title");
    const message = document.getElementById("stage-celebration-message");
    const closeButton = document.getElementById("stage-celebration-close");

    if (!celebration || !title || !message || !closeButton) return;

    const storageKey = "nudisetu-celebrated-stages";
    let celebrated = [];

    try {
      celebrated = JSON.parse(localStorage.getItem(storageKey) || "[]");
      if (!Array.isArray(celebrated)) celebrated = [];
    } catch {
      celebrated = [];
    }

    const newlyCompletedStage = Object.entries(stages).find(
      ([key, stage]) =>
        stage.categories.every((category) => completed.includes(category)) &&
        !celebrated.includes(key),
    );

    if (!newlyCompletedStage) return;

    const [key, stage] = newlyCompletedStage;

    title.textContent = `🎉 ${stage.title} stage completed!`;

    message.textContent =
      key === "beginner"
        ? "Amazing start! You're ready to build on your Kannada foundations."
        : key === "intermediate"
          ? "Wonderful progress! You're ready to practise more challenging Kannada."
          : "Incredible work! You've explored every learning stage. Keep practising!";

    celebration.hidden = false;

    celebrated.push(key);
    localStorage.setItem(storageKey, JSON.stringify(celebrated));

    closeButton.onclick = () => {
      celebration.hidden = true;
    };
  }

  // Check when the page loads
  checkStageCelebration();

  // Recommend the first unexplored category in the learning path
  let nextCategory = null;
  let nextStage = null;

  for (const [key, stage] of Object.entries(stages)) {
    nextCategory = stage.categories.find((category) => !isComplete(category));

    if (nextCategory) {
      nextStage = key;
      break;
    }
  }

  const title = document.getElementById("path-next-title");
  const description = document.getElementById("path-next-description");
  const continueButton = document.getElementById("path-continue-button");
  const welcome = document.getElementById("path-welcome");
  const footer = document.getElementById("path-footer");
  const why = document.getElementById("path-why");

  if (!title || !description || !continueButton) return;

  if (nextCategory) {
    title.textContent = `Next lesson: ${categoryNames[nextCategory]}`;
    description.textContent =
      `Continue your ${stages[nextStage].title.toLowerCase()} journey. ` +
      `Explore ${categoryNames[nextCategory]} to build your Kannada skills.`;
    if (why) {
      const exploredInStage = stages[nextStage].categories.filter((category) =>
        isComplete(category),
      ).length;

      why.textContent =
        `Why this lesson? You've explored ${exploredInStage} of 4 ` +
        `${stages[nextStage].title.toLowerCase()} categories. ` +
        `This is your next recommended step.`;
    }
    continueButton.textContent = "Continue learning →";
    continueButton.onclick = () => openPathLesson(nextCategory);

    if (welcome) {
      welcome.textContent =
        `${completed.length} of 12 categories explored. ` +
        "Your next recommendation is based on your progress.";
    }

    if (footer) {
      footer.textContent =
        "Complete a category to update your learning path and unlock your next milestone.";
    }
  } else {
    title.textContent = "You've explored all 12 categories! 🎉";
    description.textContent =
      "Amazing progress! Revisit a lesson, practise speaking, or challenge yourself with a quiz.";
    if (why) {
      why.textContent =
        "Why this next step? You've explored every category. " +
        "Now strengthen your skills through speaking practice and revision.";
    }
    continueButton.textContent = "Revisit a lesson ↻";
    continueButton.onclick = () => {
      openPathLesson("culture");
    };

    if (welcome) {
      welcome.textContent =
        "All 12 learning categories explored. Keep practising to build confidence.";
    }

    if (footer) {
      footer.textContent =
        "Your next goal: strengthen your speaking skills and revisit challenging phrases.";
    }
  }

  // Connect each stage button to an appropriate lesson
  document.querySelectorAll("[data-path-stage]").forEach((button) => {
    const key = button.dataset.pathStage;
    const stage = stages[key];

    if (!stage) return;

    button.onclick = () => {
      const category =
        stage.categories.find((item) => !isComplete(item)) ||
        stage.categories[0];

      openPathLesson(category);
    };
  });
}

function openPathLesson(category) {
  // Save progress and refresh the recommendation
  saveCompletedLesson(category);

  if (typeof openLesson === "function") {
    openLesson(category);

    const lessonPanel = document.getElementById("lesson-panel");

    if (lessonPanel) {
      lessonPanel.scrollIntoView({
        behavior: "smooth",
        block: "start",
      });
    }
  } else {
    const card = document.querySelector(`[data-category="${category}"]`);

    if (card) {
      card.click();
    } else {
      console.error("NudiSetu could not find category:", category);
    }
  }
}
