function openLesson(category) {
  const lesson = lessons[category];

  if (!lesson) return;

  lessonTitle.textContent = lesson.title;
  lessonIntro.textContent = lesson.intro;
  phraseList.replaceChildren();

  lesson.phrases.forEach((phrase) => {
    const item = document.createElement("article");
    item.className = "phrase-item";

    const details = document.createElement("div");

    const kannada = document.createElement("div");
    kannada.className = "phrase-kannada";
    kannada.lang = "kn";
    kannada.textContent = phrase.kn;

    const meaning = document.createElement("div");
    meaning.className = "phrase-meaning";
    meaning.textContent = phrase.en;

    const pronunciation = document.createElement("div");
    pronunciation.className = "phrase-pronunciation";
    pronunciation.textContent = phrase.say;

    const speakButton = document.createElement("button");
    speakButton.className = "speak-button";
    speakButton.type = "button";
    speakButton.textContent = "🔊 Listen";
    speakButton.setAttribute("aria-label", `Listen to ${phrase.en} in Kannada`);

    speakButton.addEventListener("click", () => {
      speakKannada(phrase.kn, speakButton);
    });

    details.append(kannada, meaning, pronunciation);
    item.append(details, speakButton);
    phraseList.appendChild(item);
  });

  const conversation = conversationLessons[category];
  console.log("Selected category:", category);
  console.log("Matching conversation:", conversation);

  if (conversation && document.getElementById("conversation-kannada")) {
    document.getElementById("conversation-situation").textContent =
      conversation.situation;

    document.getElementById("conversation-kannada").textContent =
      conversation.kannada;
    document.getElementById("conversation-question-text").textContent =
      `What does "${conversation.kannada}" mean?`;
    document.getElementById("conversation-pronunciation").textContent =
      conversation.pronunciation;

    document.getElementById("conversation-meaning").textContent =
      conversation.meaning;

    const optionsContainer = document.getElementById("conversation-options");
    optionsContainer.replaceChildren();

    conversation.options.forEach((option, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "conversation-option";
      button.textContent = option;

      button.addEventListener("click", () => {
        optionsContainer.querySelectorAll("button").forEach((item) => {
          item.disabled = true;
        });

        const feedback = document.getElementById("conversation-feedback");

        if (index === conversation.correctIndex) {
          feedback.textContent = "Correct! 🎉 Great job!";
          feedback.style.color = "#287344";
        } else {
          feedback.textContent = `Not quite! The correct answer is: ${conversation.options[conversation.correctIndex]}`;
          feedback.style.color = "#b45309";
        }

        const retryButton = document.createElement("button");
        retryButton.type = "button";
        retryButton.className = "primary-button";
        retryButton.textContent = "Try again ↻";

        retryButton.addEventListener("click", () => {
          openLesson(category);
        });

        feedback.appendChild(retryButton);
      });

      optionsContainer.appendChild(button);
    });

    document.getElementById("conversation-feedback").textContent = "";
  }

  lessonPanel.hidden = false;
  lessonPanel.scrollIntoView({ behavior: "smooth", block: "start" });
}

function speakKannada(text, button) {
  if (!("speechSynthesis" in window)) {
    alert("Speech playback is not supported by this browser.");
    return;
  }

  const synth = window.speechSynthesis;
  synth.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = "kn-IN";
  utterance.rate = 0.85;

  const originalText = button.textContent;
  button.textContent = "▶ Playing";

  utterance.onend = () => {
    button.textContent = originalText;
  };

  utterance.onerror = (event) => {
    button.textContent = originalText;
    console.error("Kannada speech error:", event.error);
    alert(
      "This device cannot play Kannada speech right now. " +
        "Please use the pronunciation guide below.",
    );
  };

  // Wait for the browser to finish loading its available voices.
  const speak = () => {
    synth.speak(utterance);
  };

  if (synth.getVoices().length > 0) {
    speak();
  } else {
    synth.addEventListener(
      "voiceschanged",
      function onVoicesChanged() {
        synth.removeEventListener("voiceschanged", onVoicesChanged);
        speak();
      },
      { once: true },
    );

    // Fallback if the browser doesn't fire voiceschanged.
    setTimeout(() => {
      if (!utterance.__started) {
        utterance.__started = true;
        speak();
      }
    }, 1000);
  }
}

