function updateBadgeRewards() {
  const completed = getCompletedLessons();

  // Badge 1: Namma Bengaluru Explorer
  const explorerCard = document.getElementById("badge-explorer");
  const explorerStatus = document.getElementById("explorer-status");

  if (explorerCard && explorerStatus) {
    const unlocked = completed.length >= 3;

    explorerCard.classList.toggle("unlocked", unlocked);
    explorerStatus.textContent = unlocked
      ? "Unlocked 🏆"
      : `Locked 🔒 (${completed.length}/3 categories)`;
  }

  // Badge 2: Kannada Learning Warrior
  const warriorCard = document.getElementById("badge-warrior");
  const warriorStatus = document.getElementById("warrior-status");

  if (warriorCard && warriorStatus) {
    const allLevelsUnlocked =
      localStorage.getItem("nudisetu-level-2-unlocked") === "true" &&
      localStorage.getItem("nudisetu-level-3-unlocked") === "true" &&
      localStorage.getItem("nudisetu-level-4-unlocked") === "true";

    warriorCard.classList.toggle("unlocked", allLevelsUnlocked);
    warriorStatus.textContent = allLevelsUnlocked
      ? "Unlocked 🏆"
      : "Locked 🔒 (pass all 4 quiz levels)";
  }

  // Badge 3: Karnataka Culture Keeper
  const cultureCard = document.getElementById("badge-culture");
  const cultureStatus = document.getElementById("culture-status");

  if (cultureCard && cultureStatus) {
    const unlocked = completed.length >= 5 && completed.includes("culture");

    cultureCard.classList.toggle("unlocked", unlocked);
    cultureStatus.textContent = unlocked
      ? "Unlocked 🏆"
      : `Locked 🔒 (${completed.length}/5 categories; explore Culture too)`;
  }
}

updateBadgeRewards();

