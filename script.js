function showQuizQuestion() {
  const question = activeQuizQuestions[currentQuestion];

  questionAnswered = false;
  quizQuestionElement.textContent = question.question;
  quizProgressElement.textContent = `QUESTION ${currentQuestion + 1} OF ${activeQuizQuestions.length}`;
  quizFeedbackElement.textContent = "";
  nextQuestionButton.hidden = true;
  nextQuestionButton.textContent = "Next question →";
  quizOptionsElement.replaceChildren();

  question.options.forEach((option, index) => {
    const button = document.createElement("button");

    button.type = "button";
    button.className = "quiz-option";
    button.textContent = option;

    button.addEventListener("click", () => {
      checkQuizAnswer(index, button);
    });

    quizOptionsElement.appendChild(button);
  });
}

function checkQuizAnswer(selectedIndex, selectedButton) {
  if (questionAnswered) return;

  questionAnswered = true;

  const question = activeQuizQuestions[currentQuestion];
  const allButtons = quizOptionsElement.querySelectorAll(".quiz-option");

  allButtons.forEach((button) => {
    button.disabled = true;
  });

  if (selectedIndex === question.answer) {
    quizScore++;
    selectedButton.classList.add("correct");
    quizFeedbackElement.textContent = "Correct! 🎉 " + question.explanation;
  } else {
    selectedButton.classList.add("incorrect");
    allButtons[question.answer].classList.add("correct");

    quizFeedbackElement.textContent =
      "Not quite! The correct answer is " +
      question.options[question.answer] +
      ". " +
      question.explanation;
  }

  nextQuestionButton.hidden = false;

  if (currentQuestion === activeQuizQuestions.length - 1) {
    nextQuestionButton.textContent = "See my score →";
  }
}
